"""Verify every required target pack and write a reproducible validation report."""
import json
import math
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from planetx.archive import ROOT


def main():
    targets=json.loads((ROOT/'public/data/targets.json').read_text(encoding='utf-8'))
    rows=[]
    for target in targets:
        path=ROOT/'public/data'/f"{target['id']}.json"
        data=json.loads(path.read_text(encoding='utf-8'))
        frames=data['frames']
        assert len(frames)>=2, f"Not enough observations: {target['name']}"
        assert [f['mjd'] for f in frames]==sorted(f['mjd'] for f in frames)
        assert frames[-1]['mjd']-frames[0]['mjd']>30, 'No multi-epoch baseline'
        assert all(f['wavelength_um'] and f['wavelength_um']>0 for f in frames), 'Missing spectral WCS'
        for frame in frames:
            assert len(frame['pixels'])==data['width']*data['height']
            assert all(v is None or math.isfinite(v) for v in frame['pixels'])
            assert frame['cutout_url'].startswith('https://irsa.ipac.caltech.edu/ibe/data/spherex/')
        waves=[f['wavelength_um'] for f in frames]
        # Match the frontend reference selection exactly, then verify its time baseline.
        groups=[[f for f in frames if abs(f['wavelength_um']/ref['wavelength_um']-1)<=.05+1e-10] for ref in frames]
        group=max(groups,key=lambda g:(g[-1]['mjd']-g[0]['mjd'])*100+len(g))
        span=group[-1]['mjd']-group[0]['mjd']
        assert len(group)>=2 and span>30, f"No useful wavelength-matched baseline: {target['name']}"
        rows.append(f"| {target['name']} | {len(frames)} | {data['detector']} | {frames[-1]['mjd']-frames[0]['mjd']:.1f} | {min(waves):.3f}–{max(waves):.3f} | {len(group)} / {span:.1f} d |")
    report='''# Data validation

Generated by `python scripts/validate_samples.py` on DATE.
These are real SPHEREx cutouts from IRSA. Source FITS URLs, dates, processing
versions, wavelengths and masks are recorded inside each target JSON file.

| Target | Usable frames | Array | Baseline (days) | Center wavelength range (µm) | Default ±5% match / baseline |
| --- | ---: | --- | ---: | --- | --- |
'''.replace('DATE',datetime.now(timezone.utc).isoformat())+'\n'.join(rows)+'''

Verified: five required targets; chronological frames; finite or explicitly masked
pixels; consistent pixel-grid dimensions; nonempty spectral WCS; multi-epoch
baselines; and at least two wavelength-matched frames over more than 30 days.

These checks validate data delivery and processing structure, not an astronomical
discovery or a measured motion/variability detection. Browser visual QA remains
unverified because this session's browser automation cannot read the current URL.
'''
    (ROOT/'docs/VALIDATION.md').write_text(report,encoding='utf-8')
    print(report)


if __name__=='__main__': main()
